'use strict';
const assert = require('node:assert/strict');

module.exports = async ({ cdp, evaluate, wait, capture, viewport, requests }) => {
  const settled = "document.querySelector('#cards').getAttribute('aria-busy')==='false'";
  const click = selector => evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const choose = (selector, value) => evaluate(`(()=>{const input=document.querySelector(${JSON.stringify(selector)});input.value=${JSON.stringify(value)};input.dispatchEvent(new Event('change'))})()`);
  await click('[data-page=discover]');
  await wait(settled + " && document.querySelector('#cards').classList.contains('categories')");
  assert.ok(await evaluate("!document.querySelector('#discover-language-label').hidden"));
  assert.equal(await evaluate("document.querySelector('#discover-language').options.length"), 3);
  await choose('#discover-language', 'en');
  await click('#cards .card-main');
  await wait(settled + " && !document.querySelector('#more').hidden");
  assert.equal(requests.at(-1).language, 'en');
  await click('#more');
  await wait(settled + " && document.querySelectorAll('#cards .card').length===2");
  assert.equal(requests.at(-1).cursor, 'page-two'); assert.equal(requests.at(-1).language, 'en');
  await choose('#discover-language', 'fr');
  await wait(settled + " && !document.querySelector('#empty-state').hidden");
  assert.equal(requests.at(-1).cursor, ''); assert.equal(requests.at(-1).language, 'fr');
  assert.ok(await evaluate("document.querySelector('#empty-state').textContent.includes('No streams in this language.')"));
  await click('#empty-state button');
  await wait(settled + " && document.querySelectorAll('#cards .card').length===1");
  assert.equal(requests.at(-1).language, '');
  await choose('#discover-language', 'en');
  await wait(settled);
  await capture('twitch-category-english-desktop');
  await choose('#platform', 'kick');
  await wait(settled + " && document.querySelector('#cards').classList.contains('categories')");
  await click('#cards .card-main');
  await wait(settled + " && !document.querySelector('#cards').classList.contains('categories')");
  assert.equal(requests.at(-1).platform, 'kick'); assert.equal(requests.at(-1).language, 'en');
  await viewport(390);
  assert.ok(await evaluate("(()=>{const r=document.querySelector('#discover-language').getBoundingClientRect();return r.width>100 && r.left>=0 && r.right<=innerWidth && document.documentElement.scrollWidth<=innerWidth})()"), 'language filter stays usable without horizontal scrolling on mobile');
  await capture('kick-category-english-mobile');
  await choose('#discover-language', 'fr');
  await wait(settled + " && !document.querySelector('#empty-state').hidden");
  await choose('#platform', 'twitch');
  await wait(settled + " && document.querySelector('#cards').classList.contains('categories')");
  await click('#cards .card:nth-child(2) .card-main');
  await wait(settled);
  await choose('#discover-language', '');
  await wait(settled);
  await click('#breadcrumbs button');
  await wait(settled + " && document.querySelector('#cards').classList.contains('categories')");
  await click('#cards .card-main');
  await wait(settled);
  assert.equal(requests.at(-1).language, 'en', 'returning to the first category restores its own language');
  await cdp('Page.reload');
  await wait("document.querySelector('#studio')?.dataset.page==='following' && " + settled + " && document.querySelectorAll('#cards .card').length===6");
  await click('[data-page=discover]');
  await wait(settled + " && document.querySelector('#cards').classList.contains('categories')");
  await choose('#discover-language', 'en');
  await click('#cards .card:nth-child(2) .card-main');
  await wait(settled);
  assert.equal(requests.at(-1).language, '', 'saved All languages overrides a nonempty directory choice after reload');
  await click('#breadcrumbs button');
  await wait(settled + " && document.querySelector('#cards').classList.contains('categories')");
  await click('#cards .card-main');
  await wait(settled);
  assert.equal(requests.at(-1).language, 'en', 'the original category keeps English after reconnecting');
  await choose('#platform', 'kick');
  await wait(settled + " && document.querySelector('#cards').classList.contains('categories')");
  await click('#cards .card-main');
  await wait(settled + " && !document.querySelector('#empty-state').hidden");
  assert.equal(requests.at(-1).language, 'fr', 'the same category ID on Kick has its own saved language');
  await click('[data-page=following]');
  await wait(settled + " && document.querySelector('#studio').dataset.page==='following'");
  assert.ok(await evaluate("document.querySelector('#discover-language-label').hidden"));
  assert.deepEqual(await evaluate('window.visualErrors'), []);
  console.log('PASS discovery language: category persistence across reloads, platform isolation, pagination, filter reset, mobile layout');
};
